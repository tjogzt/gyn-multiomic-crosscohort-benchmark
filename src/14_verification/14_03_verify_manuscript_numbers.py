"""
Verify that every number the manuscript quotes is produced by an artefact.

Purpose
    Stage 14, third script. The Methods and Results sections quote several
    hundred derived numbers. This script builds the list of those numbers
    automatically -- each candidate is read out of the artefact that produced it
    -- and then checks whether the value occurs in the manuscript text. Nothing
    is compared against a hand-written list: the candidate list is generated by
    walking the artefacts, so the check follows whatever the analysis actually
    produced, and a miss means either a typesetting difference or a number that
    has drifted from its source.

    Comparison is done on normalised text, because the manuscript typesets a
    minus sign as a Unicode minus and drops the trailing zeros of four-decimal
    values. The sample-intersection sizes are compared verbatim, since an
    integer has no alternative spelling.

Author
    Tao Zhu

Created
    2026-09-13

Inputs
    manuscript("methods")                Markdown source of the Methods section.
    manuscript("results")                Markdown source of the Results section.
    work("benchmark_summary")            JSON, layer-count curve and method table.
    work("pac_aggregate")                JSON, PAC stability per method.
    work("alignment_concordance")        JSON, per-layer profile concordance.
    work("protein_bridge_anchors")       JSON, mRNA-protein anchor.
    work("protein_bridge_three_cohort")  JSON, three-cohort protein bridge.
    work("benchmark_availability")       JSON, samples per domain and layer subset.
    config/legacy_label_map.yaml         Legacy domain keys of the summary table.
    config/params.yaml
        verification.core_set_reductions Counts behind the reported reductions.

Outputs
    None. The summary and the list of misses are printed to standard output.

Usage
    python 14_03_verify_manuscript_numbers.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from common.config import CONFIG, PROJECT_ROOT, param, work


def manuscript(key: str) -> Path:
    """Resolve a manuscript source declared under ``paths.manuscript``.

    Args
        key: entry name inside the manuscript section of config/paths.yaml.

    Returns
        Absolute path of the manuscript source.
    """
    root = Path(str(CONFIG["paths"]["manuscript_root"]))
    if not root.is_absolute():
        root = PROJECT_ROOT / root
    return root / CONFIG["paths"]["manuscript"][key]


def load_json(path: Path):
    """Read one JSON artefact.

    Args
        path: absolute path of the artefact.

    Returns
        The decoded object.
    """
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def load_legacy_labels() -> dict:
    """Load the legacy artefact-label map, config/legacy_label_map.yaml.

    The legacy pipeline wrote the keys of bench_summary.json and of
    bench_availability.json as Chinese labels. Those strings are lookup keys
    rather than prose -- the only correct rendering is the one that matches the
    artefact -- so they are data and live in a data file instead of in this
    module.

    Returns
        The label map, one entry per label section.
    """
    path = PROJECT_ROOT / "config" / "legacy_label_map.yaml"
    with path.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def normalise(text: str) -> str:
    """Normalise a token so that it can be compared with the manuscript text.

    Args
        text: a value read off an artefact, or the manuscript text itself.

    Returns
        The text with every dash folded to an ASCII hyphen and, for a plain
        decimal number, with trailing zeros removed.

    Notes
        The manuscript typesets a minus as U+2212 and ranges with en and em
        dashes, all of which stand for the same character as the ASCII hyphen
        Python writes when it formats a negative float. A four-decimal artefact
        value also prints trailing zeros that the manuscript drops, e.g. 0.5000
        against 0.5.
    """
    text = text.replace("\u2212", "-").replace("\u2013", "-").replace("\u2014", "-")
    if re.fullmatch(r"-?\d+\.\d+", text):
        text = text.rstrip("0").rstrip(".")
    return text


def main() -> None:
    """Build the candidate list from the artefacts and report the misses."""
    sources = {}
    for key in ["methods", "results"]:
        sources[key] = manuscript(key).read_text(encoding="utf-8")
    # The two sections are searched as one document: the manuscript may quote a
    # value in either of them, and the check only asks whether the value occurs.
    combined = "\n".join(sources.values())
    normalised_text = normalise(combined)

    summary = load_json(work("benchmark_summary"))
    pac = load_json(work("pac_aggregate"))
    concordance = load_json(work("alignment_concordance"))
    anchors = load_json(work("protein_bridge_anchors"))
    bridge = load_json(work("protein_bridge_three_cohort"))
    availability = pd.DataFrame(load_json(work("benchmark_availability")))
    legacy = load_legacy_labels()

    checks = []

    def record(label, value, source, fmt="{:.4f}"):
        """Append one check.

        Args
            label: human-readable name of the quantity.
            value: the value read off the artefact.
            source: name of the artefact the value came from.
            fmt: format applied to a numeric value before the search.

        Returns
            None. The check is appended to ``checks``.
        """
        text = (
            fmt.format(value)
            if isinstance(value, (int, float, np.floating))
            else str(value)
        )
        checks.append((label, text, source, normalise(text) in normalised_text))

    # Layer-count curve (tab3). The domain keys of the summary artefact are
    # legacy labels, so they are read from the label map rather than written
    # here; the short letter is the key used in the report label.
    for legacy_key, short_key in legacy["benchmark_domain"].items():
        for row in summary["tab3"][legacy_key]:
            record(f"layer curve {short_key} nL={row['nL']}", row["ari"], "bench_summary.tab3")

    # Method table (tab1).
    for method, values in summary["tab1"].items():
        record(f"Table 1 {method} all", values["all"], "bench_summary.tab1")
        record(f"Table 1 {method} bal", values["bal"], "bench_summary.tab1")
        record(f"Table 1 {method} deg", values["deg"], "bench_summary.tab1")

    # PAC stability per method.
    for method, values in pac["tab1"].items():
        record(f"PAC {method} all", values["all"], "pac_agg.tab1")
        record(f"PAC {method} strong", values["strong"], "pac_agg.tab1")

    # Cross-cohort alignment: the layer and pair keys are the artefact's own
    # keys and are carried into the label so a miss can be traced back.
    for layer, pairs in concordance.items():
        for pair, values in pairs.items():
            record(f"alignment {layer} {pair}", values["rho"], "align_concordance", "{:.4f}")
    for key, values in bridge["raw"].items():
        record(f"protein raw {key}", values["rho"], "bridge_3cohort.raw")
    for key, values in bridge["delta"].items():
        record(f"protein delta {key}", values["rho"], "bridge_3cohort.delta")
    # The four anchor identities are named fields of the anchor artefact: they
    # select what is reported and are not themselves under test.
    for key in ["dis_dProt_dRNA", "ind_dProt_dRNA", "dis_raw_Prot_RNA", "ind_raw_Prot_RNA"]:
        record(f"anchor {key}", anchors[key]["rho"], "b3_anchors")

    # Sample-intersection sizes, one per domain, cohort and layer-subset size.
    frame = availability.copy()
    frame["nL"] = frame["subset"].map(lambda value: len(str(value).split("+")))
    grouped = frame.groupby(["domain", "cohort", "nL"])["n"].max()
    for (domain, cohort, n_layers), count in grouped.items():
        checks.append(
            (
                f"sample {domain}/{cohort}/{n_layers} layers",
                str(int(count)),
                "bench_availability",
                str(int(count)) in combined,
            )
        )

    misses = [(label, value, source) for label, value, source, ok in checks if not ok]
    print(
        f"checks: {len(checks)}  passed: {len(checks) - len(misses)}  "
        f"not found: {len(misses)}\n"
    )
    if misses:
        print("Not found (decide by hand whether it is a typesetting difference or a wrong number):")
        for label, value, source in misses:
            print(f"  MISS {label:44s} artefact value={value:>10s}  ({source})")
    else:
        print("all checked values occur in the manuscript")

    # Derived-value spot check: recompute the two sample-intersection reductions
    # from the frozen counts and print them next to the percentage the manuscript
    # states. The counts are frozen verification data, so they live in
    # config/params.yaml rather than in this module.
    print("\nDerived-value spot check:")
    for item in param("verification", "core_set_reductions"):
        before, after = item["before"], item["after"]
        reduction = (before - after) / before * 100
        print(
            f"  {item['label']} {before} -> {after} reduction"
            f" = {reduction:.1f}%  (manuscript states {item['stated_percent']}%)"
        )


if __name__ == "__main__":
    main()
