"""
Verify the manuscript numbers that are taken from the earlier stage reports.

Purpose
    Stage 14, fourth script. It extends the number verification to the results
    the manuscript quotes from the batch testbed and from the cross-platform,
    purity-aware and decision-gate reports. Every numeric leaf of those
    artefacts is extracted and looked up in the manuscript text, so the check
    follows whatever the analysis produced: the candidate list is generated by
    walking the JSON trees of the artefacts and never read from a hand-written
    list. A value that does not occur in the manuscript is reported with the
    artefact path it came from, so a miss can be judged as either a typesetting
    difference or a number that drifted from its source.

Author
    Tao Zhu

Created
    2026-09-13

Inputs
    manuscript("methods")                Markdown source of the Methods section.
    manuscript("results")                Markdown source of the Results section.
    work("eeec_batch_results")           JSON, batch-correction arm metrics.
    work("platform_results_json")        JSON, cross-platform ladder and network.
    work("platform_results_alt")         JSON, fallback name of the same file.
    work("pai_aggregate")                JSON, purity-aware arms (fallback below).
    work("pai_matrix")                   JSON, purity-aware arms as stage 09 wrote
                                         them when no aggregate file exists.
    work("g2_refined")                   JSON, frozen G2 baseline and target.
    work("g3_power")                     JSON, G3 thresholds and power.
    config/params.yaml
        verification.platform_value_abs_max  Largest absolute platform value
                                         that is checked against the text.

Outputs
    None. The summary and the list of misses are printed to standard output.

Usage
    python 14_04_verify_manuscript_numbers_extended.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from common.config import CONFIG, PROJECT_ROOT, param, work


def manuscript(key: str) -> Path:
    """Resolve a manuscript source declared under ``paths.manuscript``.

    Args
        key: entry name inside the manuscript section of config/paths.yaml.

    Returns
        Absolute path of the manuscript source.
    """
    root = Path(str(CONFIG["paths"]["manuscript_root"]))
    if not root.is_absolute():
        root = PROJECT_ROOT / root
    return root / CONFIG["paths"]["manuscript"][key]


def load_json(path: Path):
    """Read one JSON artefact, raising if it is absent.

    Args
        path: absolute path of the artefact.

    Returns
        The decoded object.
    """
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def normalise(text: str) -> str:
    """Fold a Unicode minus to the ASCII hyphen Python writes for a negative.

    Args
        text: a value read off an artefact, or the manuscript text itself.

    Returns
        The text with U+2212 replaced by "-", and with trailing zeros removed
        when the whole string is a plain decimal number.

    Notes
        Only the minus is folded here, not the en and em dashes: this pass walks
        whole artefacts, whose numbers are not used as range endpoints.
    """
    text = text.replace("\u2212", "-")
    if re.fullmatch(r"-?\d+\.\d+", text):
        text = text.rstrip("0").rstrip(".")
    return text


def nested_value(node, *keys):
    """Walk ``keys`` into ``node``, returning None as soon as a step fails.

    Args
        node: the object to descend into.
        *keys: the keys to follow, outermost first.

    Returns
        The value found, or None when any step is missing.

    Notes
        Kept from the pre-refactor script, where it was written to reach a value
        nested inside an artefact whose top level is not yet known.
    """
    for key in keys:
        if isinstance(node, dict) and key in node:
            node = node[key]
        else:
            return None
    return node


def check_bounded_numbers(node, check, bound, prefix="") -> None:
    """Check every number of an artefact that could be a quoted rate.

    Args
        node: the artefact, or a subtree of it.
        check: callable ``check(label, *values)`` that records the candidates.
        bound: largest absolute value that counts as a quotable rate.
        prefix: dotted path accumulated so far, used as part of the label.

    Returns
        None. The surviving values are handed to ``check``.
    """
    if isinstance(node, dict):
        for key, value in node.items():
            check_bounded_numbers(value, check, bound, f"{prefix}.{key}")
    elif isinstance(node, (int, float)) and abs(node) <= bound:
        # Only values inside the unit interval are checked: anything larger is a
        # count, a sample size or a pair count, which this report does not
        # compare against the text. The values are rounded to the four decimals
        # the manuscript prints.
        check(f"platform{prefix}", round(float(node), 4))


def check_all_numbers(node, check, prefix="", list_limit: int = 40) -> None:
    """Check every number of an artefact, descending into list entries too.

    Args
        node: the artefact, or a subtree of it.
        check: callable ``check(label, *values)`` that records the candidates.
        prefix: dotted path accumulated so far, used as part of the label.
        list_limit: number of list entries followed per level; it caps how much
            of a long array can reach the report.

    Returns
        None. The values found are handed to ``check``.
    """
    if isinstance(node, dict):
        for key, value in node.items():
            check_all_numbers(value, check, f"{prefix}.{key}", list_limit)
    elif isinstance(node, (int, float)):
        check(f"{prefix}", round(float(node), 4))
    elif isinstance(node, list):
        for index, value in enumerate(node[:list_limit]):
            check_all_numbers(value, check, f"{prefix}[{index}]", list_limit)


def main() -> None:
    """Extract the candidate numbers and report the ones missing from the text."""
    text = "".join(manuscript(key).read_text(encoding="utf-8") for key in ["methods", "results"])
    normalised_text = normalise(text)

    def present(value) -> bool:
        """Return True when ``value`` occurs in the normalised manuscript text."""
        return normalise(str(value)) in normalised_text

    findings = []

    def check(label, *values):
        """Append one row: which of ``values`` are absent from the manuscript.

        Args
            label: human-readable name of the quantity.
            *values: candidate values read off an artefact.

        Returns
            None. The row is appended to ``findings``.
        """
        missing = [value for value in values if not present(value)]
        findings.append((label, missing))

    # Batch testbed: the metric columns are named differently in different
    # revisions of the artefact, so every spelling of a column is accepted and
    # only the numeric ones are checked.
    batch = load_json(work("eeec_batch_results"))
    arms = batch if isinstance(batch, list) else batch.get("arms", batch.get("rows", []))
    if isinstance(arms, list) and arms:
        for row in arms:
            name = row.get("arm") or row.get("name") or row.get("method")
            values = [
                row.get(key)
                for key in [
                    "centroid_auc",
                    "centroidAUC",
                    "total_sep",
                    "totalSep",
                    "knn_mix",
                    "knnMix",
                    "mix",
                ]
                if key in row
            ]
            check(f"batch {name}", *[value for value in values if isinstance(value, (int, float))])
    else:
        print(
            "[!] batch_results.json structure not recognised:",
            list(batch)[:8] if isinstance(batch, dict) else type(batch),
        )

    # Platform comparability. The fallback name is tried only when the live file
    # is absent, which is how the pre-refactor script addressed both revisions.
    for key in ["platform_results_json", "platform_results_alt"]:
        path = work(key)
        if path.exists():
            check_bounded_numbers(load_json(path), check, param("verification", "platform_value_abs_max"))
            break
    else:
        print("[!] no platform results JSON")

    # Purity-aware arms (P2). Only the two declared names are tried, and the
    # loop stops at the first file that exists.
    for key in ["pai_aggregate", "pai_matrix"]:
        path = work(key)
        if path.exists():
            pai = load_json(path)
            if isinstance(pai, dict) and "arms" in pai:
                for row in pai["arms"]:
                    check(
                        "purity " + str(row.get("arm") or row.get("name")),
                        *[
                            round(row[column], 4)
                            for column in row
                            if column in ("dARI", "delta", "dari")
                            and isinstance(row[column], (int, float))
                        ],
                    )
            break

    # G2 and G3 decision-gate artefacts. The artefact is labelled by its file
    # name, so a miss can be traced back to the file it came from. The key list
    # of each element names the fields of interest but is not used by the walk,
    # which checks every number; it is kept as the pre-refactor script declared
    # it.
    for key, keys in [
        (
            "g2_refined",
            ["baseline", "threshold", "target", "ci_lo", "ci_hi", "n_units", "n_needed"],
        ),
        ("g3_power", []),
    ]:
        check_all_numbers(load_json(work(key)), check, work(key).name)

    misses = [(label, missing) for label, missing in findings if missing]
    print(
        f"\nchecks: {len(findings)}   fully found: {len(findings) - len(misses)}"
        f"   with a miss: {len(misses)}"
    )
    for label, missing in misses[:40]:
        print(f"  ~ {label}: not in the manuscript {[str(value) for value in missing[:6]]}")


if __name__ == "__main__":
    main()
